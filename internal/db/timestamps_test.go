// TestFormatTimestamp_IsWhatSQLiteCanRead is the whole of #33 in one
// assertion: the text a write puts in a DATETIME column has to be something
// SQLite's own date functions can parse.
func TestFormatTimestamp_IsWhatSQLiteCanRead(t *testing.T) {
	database, err := Open(t.TempDir())
	if err != nil {
		t.Fatalf("open db: %v", err)
	}
	defer func() { _ = database.Close() }()

	instant := time.Date(2026, 1, 14, 20, 15, 0, 134000000, time.UTC)
	stored := FormatTimestamp(instant)

	if want := "2026-01-14T20:15:00.134000000Z"; stored != want {
		t.Errorf("FormatTimestamp = %q, want %q", stored, want)
	}

	var date, datetime, month, julian any
	err = database.QueryRow(
		`SELECT date(?1), datetime(?1), strftime('%Y-%m', ?1), julianday(?1)`, stored,
	).Scan(&date, &datetime, &month, &julian)
	if err != nil {
		t.Fatalf("run date functions: %v", err)
	}
	for name, got := range map[string]any{
		"date": date, "datetime": datetime, "strftime": month, "julianday": julian,
	} {
		if got == nil {
			t.Errorf("%s(%q) is NULL; SQLite cannot read the stored rendering", name, stored)
		}
	}
	if date != "2026-01-14" {
		t.Errorf("date() = %v, want 2026-01-14", date)
	}
	if month != "2026-01" {
		t.Errorf("strftime('%%Y-%%m') = %v, want 2026-01", month)
	}
}

// TestFormatTimestamp_NormalisesToUTC is the half of #90 that lives in the
// rendering. A bound and a stored value that carry different offsets can only
// be compared as instants if both are rendered in the same zone.
func TestFormatTimestamp_NormalisesToUTC(t *testing.T) {
	kolkata := time.FixedZone("IST", 5*3600+1800)
	local := time.Date(2026, 10, 1, 7, 30, 0, 0, kolkata)
	utc := local.UTC()

	if got, want := FormatTimestamp(local), FormatTimestamp(utc); got != want {
		t.Errorf("the same instant rendered two ways: %q and %q", got, want)
	}
	if want := "2026-10-01T02:00:00.000000000Z"; FormatTimestamp(local) != want {
		t.Errorf("FormatTimestamp(%v) = %q, want %q", local, FormatTimestamp(local), want)
	}
}

// TestFormatTimestamp_SortsChronologically is why the fraction is fixed-width
// rather than time.RFC3339Nano's trimmed one.
//
// RFC3339Nano drops trailing zeros, so a whole second renders as
// "…:05Z" and a tenth past it as "…:05.1Z" — and '.' (0x2E) sorts before
// 'Z' (0x5A), which puts the later instant first. ORDER BY t.timestamp,
// MIN()/MAX() over the column and the date-filter predicate are all
// lexicographic comparisons of this text, so a format that does not sort is a
// format that returns the wrong rows.
func TestFormatTimestamp_SortsChronologically(t *testing.T) {
	base := time.Date(2026, 3, 1, 12, 0, 5, 0, time.UTC)
	instants := []time.Time{
		base,
		base.Add(1 * time.Nanosecond),
		base.Add(90 * time.Millisecond),
		base.Add(100 * time.Millisecond),
		base.Add(120 * time.Millisecond),
		base.Add(1 * time.Second),
		base.Add(24 * time.Hour),
	}

	rendered := make([]string, len(instants))
	for i, instant := range instants {
		rendered[i] = FormatTimestamp(instant)
	}

	sorted := append([]string(nil), rendered...)
	sort.Strings(sorted)
	for i := range sorted {
		if sorted[i] != rendered[i] {
			t.Fatalf("text order disagrees with time order at %d:\n text: %v\n time: %v", i, sorted, rendered)
		}
	}
}

// TestFormatTimestamp_LeavesSearchPeriodAlone is the coupling that decided the
// format. turns.search_period and tool_uses.search_period are generated by
// slicing the timestamp text, and both FTS indexes hold those slices. A
// rendering that moved the year, month or day out from under substr() would
// turn a storage migration into a rebuild of two million-document indexes.
func TestFormatTimestamp_LeavesSearchPeriodAlone(t *testing.T) {
	database, err := Open(t.TempDir())
	if err != nil {
		t.Fatalf("open db: %v", err)
	}
	defer func() { _ = database.Close() }()

	instant := time.Date(2026, 8, 14, 20, 15, 0, 134000000, time.UTC)
	legacy := instant.String() // "2026-08-14 20:15:00.134 +0000 UTC"
	canonical := FormatTimestamp(instant)

	const periodExpr = `
		SELECT CASE WHEN ?1 GLOB '[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]*'
		            THEN 'ccvd' || substr(?1, 1, 4) || substr(?1, 6, 2) || substr(?1, 9, 2)
		                 || ' ccvym' || substr(?1, 1, 4) || substr(?1, 6, 2)
		            ELSE 'ccvymx' END`

	var before, after string
	if err := database.QueryRow(periodExpr, legacy).Scan(&before); err != nil {
		t.Fatalf("period of legacy rendering: %v", err)
	}
	if err := database.QueryRow(periodExpr, canonical).Scan(&after); err != nil {
		t.Fatalf("period of canonical rendering: %v", err)
	}
	if before != after {
		t.Errorf("search_period changed with the rendering: %q -> %q", before, after)
	}
	if want := "ccvd20260814 ccvym202608"; after != want {
		t.Errorf("search_period = %q, want %q", after, want)
	}
}

// TestFormatTimestamp_RoundTripsThroughTheDriver guards the read half, and it
// has to go through a real DATETIME column to say anything: modernc's driver
// only attempts a time parse when the column's declared type is DATE, DATETIME
// or TIMESTAMP, so a `SELECT ?` probe would be asserting about a different
// code path than every read in this package takes.
//
// A rendering the driver cannot guess at arrives as a zero time rather than an
// error, which is the quiet failure this is here to catch.
func TestFormatTimestamp_RoundTripsThroughTheDriver(t *testing.T) {
	database, err := Open(t.TempDir())
	if err != nil {
		t.Fatalf("open db: %v", err)
	}
	defer func() { _ = database.Close() }()

	instant := time.Date(2026, 5, 2, 3, 4, 5, 678901234, time.UTC)
	if err := database.UpsertSourceFileMtime("/probe.jsonl", instant, "claude-code"); err != nil {
		t.Fatalf("upsert source file mtime: %v", err)
	}

	var back time.Time
	if err := database.QueryRow("SELECT mtime FROM source_files WHERE path = ?", "/probe.jsonl").Scan(&back); err != nil {
		t.Fatalf("scan into time.Time: %v", err)
	}
	if !back.Equal(instant) {
		t.Errorf("round trip lost the instant: stored %v, read back %v", instant, back)
	}
}

// TestFormatTimestamp_DropsTheMonotonicClock covers #33's third bullet.
// time.Now() carries a monotonic reading that String() renders as " m=+4.49",
// which is what source_files.mtime held.
func TestFormatTimestamp_DropsTheMonotonicClock(t *testing.T) {
	now := time.Now()
	rendered := FormatTimestamp(now)

	if len(rendered) != len(timestampLayout) {
		t.Errorf("FormatTimestamp(time.Now()) = %q, want the fixed-width canonical layout", rendered)
	}
	if parsed, err := ParseTimestamp(rendered); err != nil {
		t.Errorf("ParseTimestamp(%q): %v", rendered, err)
	} else if !parsed.Equal(now.Round(0).Truncate(time.Nanosecond)) {
		t.Errorf("round trip of time.Now() lost the instant: %v vs %v", now, parsed)
	}
}
